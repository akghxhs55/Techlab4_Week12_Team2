#pragma once

// Shared application version for C++ and Windows resource scripts.
// Windows version components must be in the range 0..65535.
#define KURISU_VERSION_MAJOR 1
#define KURISU_VERSION_MINOR 0
#define KURISU_VERSION_PATCH 0
#define KURISU_VERSION_REVISION 0

#define KURISU_VERSION_STRINGIFY_IMPL(Value) #Value
#define KURISU_VERSION_STRINGIFY(Value) KURISU_VERSION_STRINGIFY_IMPL(Value)

#define KURISU_VERSION_TUPLE \
    KURISU_VERSION_MAJOR, KURISU_VERSION_MINOR, KURISU_VERSION_PATCH, KURISU_VERSION_REVISION

#define KURISU_VERSION_STRING \
    KURISU_VERSION_STRINGIFY(KURISU_VERSION_MAJOR) "." \
    KURISU_VERSION_STRINGIFY(KURISU_VERSION_MINOR) "." \
    KURISU_VERSION_STRINGIFY(KURISU_VERSION_PATCH) "." \
    KURISU_VERSION_STRINGIFY(KURISU_VERSION_REVISION)
